import { mkdtemp, writeFile, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { createProject, projectDir } from '../src/store.js';
import { Runner } from '../src/runner.js';
import { openCodeEntry, capture, providerEnv } from '../src/integrations.js';
const root = await mkdtemp(join(tmpdir(), 'reaw-real-smoke-'));
process.env.REAW_HOME = join(root, 'storage');
const target = join(root, 'sample');
const { mkdir } = await import('node:fs/promises'); await mkdir(target);
await writeFile(join(target, 'package.json'), JSON.stringify({ name: 'synthetic-analysis-fixture', version: '1.0.0', type: 'module', main: 'index.js' }));
await writeFile(join(target, 'index.js'), 'export function add(a,b) { return a+b; }');
const project = await createProject({ name: 'Synthetic smoke', goal: 'Validate real REA integration', scope: 'Self-created fixture only', authorized: true });
const runner = new Runner(); const run = await runner.start(project.id, { kind: 'javascript', target }); const result = await runner.pending;
assert.equal(result.status, 'completed', result.error);
const evidence = JSON.parse(await readFile(join(projectDir(project.id), 'runs', run.id, 'evidence.json'), 'utf8'));
assert.equal(evidence.operation, 'analyze_javascript_application');
const agent = await capture(openCodeEntry(), ['--version'], providerEnv({}), 20000); assert.equal(agent.ok, true, agent.error);
console.log(`Real REA static analysis passed; OpenCode ${agent.output.trim()} starts. No model call or native provider was tested here.`);
